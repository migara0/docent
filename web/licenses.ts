import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { Plugin } from 'vite';

// Writes the licence of every npm package that ends up in the built UI (and so inside the docent binary) to one file.
// It looks at the modules Rollup actually bundled, so packages that are only used to build or test are left out.

interface Pkg { name: string; version: string; license: string; url: string; text: string }

function packageRoot(id: string): string | undefined {
  const file = id.replace(/^\0/, '').split('?')[0]!;
  const at = file.lastIndexOf('/node_modules/');
  if (at < 0) return undefined;
  const rest = file.slice(at + '/node_modules/'.length).split('/');
  const depth = rest[0]!.startsWith('@') ? 2 : 1;
  return file.slice(0, at + '/node_modules/'.length) + rest.slice(0, depth).join('/');
}

function read(root: string): Pkg {
  const pj = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')) as Record<string, unknown>;
  const repo = pj.repository as string | { url?: string } | undefined;
  const url = String(pj.homepage ?? (typeof repo === 'string' ? repo : repo?.url) ?? '')
    .replace(/^git\+/, '')
    .replace(/\.git$/, '')
    .replace(/^git:\/\//, 'https://')
    .replace(/^github:/, '')
    .replace(/^([\w.-]+\/[\w.-]+)$/, 'https://github.com/$1'); // "owner/repo" shorthand
  const file = readdirSync(root).find((f) => /^(licen[cs]e|copying)/i.test(f));
  const text = file ? readFileSync(join(root, file), 'utf8').trim() : '';
  // a package without a licence field states it in its licence file
  const license = typeof pj.license === 'string' ? pj.license : /MIT License/i.test(text) ? 'MIT' : 'see text';
  return { name: String(pj.name), version: String(pj.version), license, url, text };
}

export function thirdPartyLicenses(out: string): Plugin {
  const roots = new Set<string>();
  return {
    name: 'docent-third-party-licenses',
    apply: 'build',
    generateBundle(_, bundle) {
      for (const chunk of Object.values(bundle)) {
        if (chunk.type !== 'chunk') continue;
        for (const id of Object.keys(chunk.modules)) {
          const root = packageRoot(id);
          if (root) roots.add(root);
        }
      }
    },
    closeBundle() {
      const pkgs = [...new Map([...roots].map(read).map((p) => [`${p.name}@${p.version}`, p])).values()].sort((a, b) => a.name.localeCompare(b.name));
      const parts = [
        '# Third-party code in the Docent web interface',
        '',
        'These npm packages are compiled into the web interface that the `docent` binary embeds. Generated by `web/licenses.ts` during `pnpm build`; do not edit.',
        '',
        '| Package | Version | Licence |',
        '| ------- | ------- | ------- |',
        ...pkgs.map((p) => `| ${p.url ? `[${p.name}](${p.url})` : p.name} | ${p.version} | ${p.license} |`),
        '',
        ...pkgs.flatMap((p) => [`## ${p.name} ${p.version}`, '', p.text ? '```text\n' + p.text + '\n```' : `Licence: ${p.license} (no licence file in the package).`, '']),
      ];
      writeFileSync(out, parts.join('\n'));
    },
  };
}
