#!/usr/bin/env bash
# Writes the licence of every Go module compiled into the docent binary to licenses/THIRD_PARTY_GO.md.
# Run from the repository root (make licenses). The modules come from `go list -deps`, so test-only modules are left out.
set -euo pipefail

out=licenses/THIRD_PARTY_GO.md
self=$(go list -m)
{
  echo '# Third-party Go modules in Docent'
  echo
  echo 'These modules are compiled into the `docent` binary (Linux and Windows builds; some are only in one of them).'
  echo 'Generated by `scripts/go-licenses.sh` (`make licenses`); do not edit.'
  echo
  # every system a release is built for: a module can be used on one only (cobra uses mousetrap on Windows)
  for goos in linux windows; do
    GOOS=$goos go list -deps -f '{{if .Module}}{{.Module.Path}} {{.Module.Version}} {{.Module.Dir}}{{end}}' ./cmd/docent
  done | sort -u | grep -v "^$self " |
    while read -r path version dir; do
      file=$(find "$dir" -maxdepth 1 -type f \( -iname 'licen[cs]e*' -o -iname 'copying*' \) | sort | head -1)
      echo "## $path $version"
      echo
      if [ -n "$file" ]; then
        echo '```text'
        cat "$file"
        echo '```'
      else
        echo "No licence file found in the module; see https://pkg.go.dev/$path?tab=licenses"
      fi
      echo
    done
} > "$out"
echo "wrote $out ($(grep -c '^## ' "$out") modules)"
